#!/usr/bin/env bash
# =============================================================================
# Compute metrics from a prediction JSONL file.
#
# Usage:
#   bash scripts/eval/metrics.sh --predictions_jsonl PATH
#   bash scripts/eval/metrics.sh --predictions_jsonl PATH --output_json results/metrics.json
#   METRIC_MODE=llm_judge JUDGE_JSONL=results/judge.jsonl bash scripts/eval/metrics.sh --predictions_jsonl PATH
#
# All parameters below can be overridden via environment variables.
# =============================================================================
set -euo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../common.sh"

# ── Input ──────────────────────────────────────────────────────────────────

PREDICTIONS_JSONL="${PREDICTIONS_JSONL:-}"

# ── Output ─────────────────────────────────────────────────────────────────

OUTPUT_JSON="${OUTPUT_JSON:-}"           # Optional metrics JSON output

# ── Metric mode ────────────────────────────────────────────────────────────

METRIC_MODE="${METRIC_MODE:-local}"      # local | none | llm_judge

# ── LLM judge ──────────────────────────────────────────────────────────────

JUDGE_JSONL="${JUDGE_JSONL:-}"           # Optional LLM-judge-ready JSONL output

# ── Help ───────────────────────────────────────────────────────────────────

print_help() {
  cat <<'EOF'
Compute metrics from a prediction JSONL file (generated by predict.sh or train.py).

Usage:
  bash scripts/eval/metrics.sh --predictions_jsonl PATH [options]

Modes:
  local      Score with built-in task parsers / code tests (default).
  none       Print prediction records without scoring.
  llm_judge  Export judge-ready JSONL records for external LLM scoring.

Examples:

  # Score predictions locally
  bash scripts/eval/metrics.sh \
    --predictions_jsonl outputs/fedweave/alpha_0p3/seed_42/checkpoints/eval/fedweave_test_predictions.jsonl

  # Save metrics to a file
  bash scripts/eval/metrics.sh \
    --predictions_jsonl outputs/.../predictions.jsonl \
    --output_json results/metrics.json

  # Export for LLM judging
  METRIC_MODE=llm_judge JUDGE_JSONL=results/judge_inputs.jsonl \
    bash scripts/eval/metrics.sh --predictions_jsonl outputs/.../predictions.jsonl

  # Just print records (no scoring)
  METRIC_MODE=none bash scripts/eval/metrics.sh --predictions_jsonl outputs/.../predictions.jsonl

All parameters can be set via environment variables (uppercase names above).
EOF
}

# ── Parse CLI ──────────────────────────────────────────────────────────────

ARGS=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --help|-h)
      print_help
      exit 0
      ;;
    --predictions_jsonl)
      PREDICTIONS_JSONL="$2"; shift 2 ;;
    --predictions_jsonl=*)
      PREDICTIONS_JSONL="${1#*=}"; shift ;;
    --output_json)
      OUTPUT_JSON="$2"; shift 2 ;;
    --output_json=*)
      OUTPUT_JSON="${1#*=}"; shift ;;
    --judge_jsonl)
      JUDGE_JSONL="$2"; shift 2 ;;
    --judge_jsonl=*)
      JUDGE_JSONL="${1#*=}"; shift ;;
    --metric_mode)
      METRIC_MODE="$2"; shift 2 ;;
    --metric_mode=*)
      METRIC_MODE="${1#*=}"; shift ;;
    *)  ARGS+=("$1"); shift ;;
  esac
done

if [[ -z "$PREDICTIONS_JSONL" ]]; then
  echo "error: --predictions_jsonl is required." >&2
  print_help
  exit 2
fi

# ── Build command ──────────────────────────────────────────────────────────

CMD_ARGS=(--predictions_jsonl "$PREDICTIONS_JSONL")
CMD_ARGS+=(--metric_mode "$METRIC_MODE")

[[ -n "$OUTPUT_JSON" ]] && CMD_ARGS+=(--output_json "$OUTPUT_JSON")
[[ -n "$JUDGE_JSONL" ]] && CMD_ARGS+=(--judge_jsonl "$JUDGE_JSONL")

# ── Run ────────────────────────────────────────────────────────────────────

"$PYTHON_BIN" "$PROJECT_DIR/src/metrics.py" "${CMD_ARGS[@]}" "${ARGS[@]}"
